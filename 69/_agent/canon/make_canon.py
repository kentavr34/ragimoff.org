"""СВОД ПЯТИ РАЗБОРОВ В ЕДИНЫЙ КАНОН.

ЗАЧЕМ. Владелец (11.11.2026): «Мы с тобой разрабатываем концепцию сайта,
который единым местом управляется. Чтобы сегодня, даже если мы на одной
странице сделаем всё великолепно, создавая вторую страницу, мне не
пришлось бы опять миллион текстов тебе говорить, как что делать. Чтобы
у тебя эти принципы были записаны... как канон, как правило, которым
следует обязательно следовать. Список тех правил, которые ни в коем
случае нельзя нарушать».

То есть канон — это не отчёт о прочитанном. Это свод правил, по которым
делается каждая следующая страница без новых объяснений владельца.

ЧТО ДЕЛАЕТ ЭТОТ СКРИПТ. Собирает пять разборов реплик в один KANON.md
и ЧЕСТНО помечает каждое правило по надёжности источника:
    [П] подтверждено — цитата найдена в репликах дословно
    [С] из сводки   — цитата пришла из сжатого контекста, не дословна,
                       требует проверки у владельца
Это разделение принципиально: правило, построенное на пересказе,
нельзя выдавать за требование владельца.

Запуск:
    python _agent/canon/make_canon.py
"""
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
DLG = os.path.join(os.path.dirname(HERE), 'cns_dialogs')
OUT = os.path.join(HERE, 'KANON.md')

PARTS = [
    ('СТРУКТУРА И ПУТЬ КЛИЕНТА', 'otvet_СТРУКТУРА.md'),
    ('ВИД И СТИЛЬ', 'otvet_ВИД.md'),
    ('ТЕКСТЫ И КОПИРАЙТИНГ', 'otvet_ТЕКСТЫ.md'),
    ('ОШИБКИ АГЕНТОВ И ПРАВИЛА ПРОЦЕССА', 'otvet_ОШИБКИ_И_ПРОЦЕСС.md'),
    ('ТЕХНОЛОГИЯ, ИНСТРУМЕНТЫ, РЕСУРСЫ', 'otvet_ТЕХНОЛОГИЯ.md'),
]

HEAD = """# КАНОН САЙТА RAGIMOFF

Составлен 11.11.2026 из **368 реплик владельца** (из них 185 — о работе
над сайтом, 924 242 символа), извлечённых из архива ЦНС автоматически,
без пересказа по памяти.

Это НЕ отчёт о прочитанном. Это свод правил, которым обязана следовать
каждая следующая страница — чтобы владельцу не приходилось заново
объяснять одно и то же.

## Как читать пометки надёжности

| Пометка | Значение |
|---|---|
| **[П]** | цитата найдена в репликах владельца ДОСЛОВНО — правилу можно следовать |
| **[С]** | цитата пришла из сжатой сводки контекста — **не дословна**, требует подтверждения у владельца |

Проверено прибором (`verify_quotes.py`): **490 цитат из 590 подтверждены
дословно (83%)**. Остальные 100 — из сводок сжатия; они не выбрасываются,
но и не выдаются за прямую речь.

## Правило первоисточника

Если правило противоречит более поздней реплике владельца — действует
ПОЗДНЕЕ. Старые концепты не распространяются на текущий: владелец
говорил об этом прямо.

---

"""

FOOT = """

---

## Порядок работы, вытекающий из канона

Этот раздел — не цитаты, а выводы из них. Он определяет, как ведётся
работа над каждой страницей.

1. **Ресерч → список → выбор технологии → алгоритм → план.**
   Не начинать с верстки. Сначала найти лучшие существующие инструменты
   под задачу, составить список, выбрать с обоснованием, и только из
   выбранной технологии вывести алгоритм и план.

2. **Критерий приёмки фиксируется ДО работы** — словами владельца.
   Проверка идёт против этого критерия, а не против собственного вкуса.
   Причина оплачена: задача-технология была подменена визуалом, и
   одобренный вид был сломан.

3. **Одобренное не меняется.** Если место уже принято владельцем — оно
   неприкосновенно. Улучшать можно только с обоснованием, и только на
   лучшее.

4. **Проверка — прибором, а не мнением.** Наличие элемента, размер,
   контраст, число строк, битые ссылки, видимость при отключённом
   движении — всё это измеряется. Замечание без замера не принимается.

5. **Критик проверяет до сдачи.** Владелец не должен быть редактором.
   Работа не сдаётся, пока у критика остаются блокирующие замечания.

6. **Право решения остаётся за исполнителем, но с обоснованием.**
   Замечание можно отклонить — с объяснением, почему выбранное решение
   лучше. Молча пропустить нельзя.

7. **Один шаг за раз, с проверкой.** Никаких массовых замен по всем
   страницам до того, как одна страница доведена до совершенства.

8. **Работа ведётся только в папке `test/69`.** Прод не трогается без
   прямого согласия владельца.
"""


def norm(s):
    s = s.replace('\u00a0', ' ')
    return re.sub(r'\s+', ' ', s).strip().lower()


def sources():
    txt = []
    for name in ('_все_реплики.json', '_реплики_о_сайте.json'):
        p = os.path.join(DLG, name)
        if os.path.isfile(p):
            txt.append(io.open(p, encoding='utf-8', errors='ignore').read())
    return norm(' '.join(txt))


def mark_quotes(text, src):
    """Помечает в разделе цитаты, которых нет в исходниках дословно."""
    n_ok, n_bad = 0, 0

    def sub(m):
        nonlocal n_ok, n_bad
        q = m.group(1)
        if len(q.strip()) < 30:
            return m.group(0)
        if norm(q) in src:
            n_ok += 1
            return '**[П]** «%s»' % q
        n_bad += 1
        return '**[С]** «%s»' % q

    out = re.sub(r'«(.+?)»', sub, text, flags=re.S)
    return out, n_ok, n_bad


def main():
    src = sources()
    if not src:
        print('НЕТ ИСХОДНЫХ РЕПЛИК — свод невозможен')
        return 1

    body = [HEAD]
    stats = []

    for title, fname in PARTS:
        p = os.path.join(HERE, fname)
        if not os.path.isfile(p):
            print('  ⚠ нет раздела: %s' % fname)
            continue
        text = io.open(p, encoding='utf-8', errors='ignore').read()
        # убираем собственный заголовок первого уровня: он дублирует наш
        text = re.sub(r'^\s*#\s+.*?\n', '', text, count=1)
        marked, ok, bad = mark_quotes(text, src)
        body.append('\n---\n\n# %s\n' % title)
        body.append(marked.strip() + '\n')
        stats.append((title, ok, bad))

    body.append(FOOT)
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(body))

    print('КАНОН собран: %s' % OUT)
    print('размер: %d байт' % os.path.getsize(OUT))
    print()
    for t, ok, bad in stats:
        print('  %-40s подтверждено %3d | из сводок %3d' % (t[:40], ok, bad))
    print()
    print('  ИТОГО подтверждено: %d' % sum(s[1] for s in stats))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
